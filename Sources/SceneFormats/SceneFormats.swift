import SceneCore
import SceneGraph


/// Exports a static triangle scene as text or binary 3DMF.
/// Each node is a display group and each submesh a TriMesh. Animation and physics are not serialized.
/// Supports color materials (Phong/Blinn, Lambert, unlit), normals and UV channel zero.
/// Textures, PBR, lights, cameras and other vertex streams are rejected.
public struct ThreeDMFEncoder: SceneAssetEncoder {
    public static let fileExtensions = ["3dmf", "3dm", "q3d"]

    /// The output encoding. Text remains the default; binary supports either byte order.
    public var encoding: Metafile3D.Encoding

    public init(encoding: Metafile3D.Encoding = .text) {
        self.encoding = encoding
    }

    public func encode(_ scene: Scene) async throws(SceneFormatError) -> [UInt8] {
        try encodeScene(scene)
    }

    public func encodeScene(_ scene: Scene) throws(SceneFormatError) -> [UInt8] {
        guard let background = scene.background.color, background.w == 1 else {
            throw .unsupported("3DMF export requires an opaque color background")
        }
        var objects = [try floats(.imageClearColor, [background.x, background.y, background.z])]
        objects += try node(scene.rootNode, depth: 0)
        if case .binary(let byteOrder) = encoding {
            var converted: [MetafileObject] = []
            for object in objects { converted.append(try binaryObject(object, byteOrder: byteOrder)) }
            objects = converted
        }
        return try Metafile3D(encoding: encoding, objects: objects).encoded()
    }


    // Serializes only the schemas generated by this encoder, not arbitrary parsed metafiles.
    // TriMesh index widths follow Quesa's E3FFW_3DMFBin_Geometry.cpp.
    // Copyright (c) 1999-2021, Quesa Developers. BSD 3-Clause; see LICENSE-Quesa.
    private func binaryObject(_ object: MetafileObject, byteOrder: Metafile3D.ByteOrder) throws(SceneFormatError) -> MetafileObject {
        var reader = object.reader()
        var bytes: [UInt8] = []
        func integer(_ value: UInt32, width: Int = 4) {
            for index in 0..<width {
                let shift = (byteOrder == .bigEndian ? width - 1 - index : index) * 8
                bytes.append(UInt8(truncatingIfNeeded: value >> shift))
            }
        }
        switch object.type {
        case .triMesh:
            var counts: [UInt32] = []
            for _ in 0..<6 {
                let count = try reader.uint32()
                counts.append(count)
                integer(count)
            }
            let triangleCount = Int(counts[0])
            let pointCount = Int(counts[4])
            guard counts[2] == 0 else { throw .unsupported("Exported TriMesh edges are not supported") }
            let width = pointCount < 256 ? 1 : pointCount < 65536 ? 2 : 4
            for _ in 0..<triangleCount * 3 { integer(try reader.uint32(), width: width) }
            for _ in 0..<pointCount * 3 + 6 { integer(try reader.float32().bitPattern) }
            integer(try reader.boolean() ? 1 : 0)
        case .attributeArray:
            for _ in 0..<5 { integer(try reader.uint32()) }
            while !reader.isAtEnd { integer(try reader.float32().bitPattern) }
        case .cString:
            bytes = Array(try reader.string().utf8) + [0]
            while bytes.count % 4 != 0 { bytes.append(0) }
        case .displayGroupState, .backfacingStyle:
            integer(try reader.uint32())
        case .imageClearColor, .matrixTransform, .diffuseColor, .specularColor,
             .emissiveColor, .specularControl, .transparencyColor:
            while !reader.isAtEnd { integer(try reader.float32().bitPattern) }
        case .displayGroup, .resetTransform, .attributeSet, .nameElement,
             .phongIllumination, .lambertIllumination, .nullIllumination:
            break
        default:
            throw .unsupported("No binary scene serializer for \(object.type)")
        }
        guard reader.isAtEnd else { throw .malformed("Unexpected scene export payload", offset: nil) }
        let data: BinaryMetafileData
        do {
            let count = bytes.count
            let range = try bytes.withParserSpan { (span) throws(ParsingError) in
                try span.sliceRange(byteCount: count)
            }
            data = BinaryMetafileData(file: bytes, range: range, byteOrder: byteOrder)
        } catch {
            throw SceneFormatError(error)
        }
        var children: [MetafileObject] = []
        for child in object.children { children.append(try binaryObject(child, byteOrder: byteOrder)) }
        return MetafileObject(type: object.type, data: .binary(data), children: children)
    }

    private func object(_ type: MetafileObjectType, _ values: [String] = [], children: [MetafileObject] = []) -> MetafileObject {
        MetafileObject(type: type, data: .text(values), children: children)
    }

    private func floats(_ type: MetafileObjectType, _ values: [Float]) throws(SceneFormatError) -> MetafileObject {
        guard values.allSatisfy(\.isFinite) else { throw .malformed("Non-finite export value", offset: nil) }
        return object(type, values.map { String($0) })
    }

    private func name(_ value: String?) throws(SceneFormatError) -> [MetafileObject] {
        guard let value else { return [] }
        guard !value.unicodeScalars.contains(where: { $0.value < 32 }) else {
            throw .unsupported("Control characters in 3DMF names")
        }
        var quoted = "\""
        for character in value {
            if character == "\\" || character == "\"" { quoted.append("\\") }
            quoted.append(character)
        }
        quoted.append("\"")
        return [object(.nameElement, children: [object(.cString, [quoted])])]
    }

    private func node(_ node: Node, depth: Int) throws(SceneFormatError) -> [MetafileObject] {
        guard depth < 50 else { throw .unsupported("Scene hierarchy is too deep to export") }
        guard node.camera == nil, node.light == nil, node.opacity == 1 else {
            throw .unsupported("Lights, cameras and node opacity are not supported by 3DMF export")
        }
        var children: [MetafileObject] = []
        if node.isHidden { children.append(object(.displayGroupState, ["2"])) }
        children += try name(node.name)
        if let geometry = node.geometry {
            for submesh in geometry.mesh.submeshes {
                guard submesh.materialIndex >= 0 else { throw .malformed("Negative material index", offset: nil) }
                let material = geometry.materials.isEmpty ? MaterialDescriptor.default
                    : geometry.materials[submesh.materialIndex % geometry.materials.count].descriptor
                children.append(try mesh(geometry.mesh, submesh: submesh, material: material))
            }
        }
        for child in node.children { children += try self.node(child, depth: depth + 1) }
        // Reset before each sibling so its matrix cannot accumulate the previous sibling's transform.
        return [object(.resetTransform), try floats(.matrixTransform, node.transform.quickDraw3DElements),
                object(.displayGroup, children: children)]
    }

    private func mesh(_ mesh: MeshBuffer, submesh: Submesh, material: MaterialDescriptor) throws(SceneFormatError) -> MetafileObject {
        guard mesh.vertexCount > 0, mesh.vertexCount < 1 << 26,
              submesh.range.lowerBound >= 0, submesh.range.upperBound <= (mesh.indices?.count ?? mesh.vertexCount),
              (submesh.primitive == .triangles && submesh.range.count >= 3 && submesh.range.count % 3 == 0)
                || (submesh.primitive == .triangleStrip && submesh.range.count >= 3) else {
            throw .unsupported("3DMF export requires valid triangle or triangle-strip submeshes")
        }
        var semantics: Set<VertexSemantic> = []
        for stream in mesh.streams {
            let components: Int
            switch stream.semantic {
            case .position, .normal: components = 3
            case .textureCoordinate(0): components = 2
            default: throw .unsupported("Vertex stream is not supported by 3DMF export")
            }
            guard semantics.insert(stream.semantic).inserted,
                  stream.componentCount == components, stream.data.count == mesh.vertexCount * components,
                  stream.data.allSatisfy(\.isFinite) else {
                throw .malformed("Invalid vertex stream", offset: nil)
            }
        }
        guard semantics.contains(.position) else { throw .malformed("Missing positions", offset: nil) }
        let triangles = mesh.triangles(in: submesh)
        guard triangles.count < 1 << 26,
              triangles.allSatisfy({ t in (0..<3).allSatisfy { t[$0] >= 0 && t[$0] < mesh.vertexCount } }) else {
            throw .malformed("Triangle index is out of range", offset: nil)
        }
        var arrays: [MetafileObject] = []
        for (semantic, type) in [(VertexSemantic.normal, 3), (.textureCoordinate(0), 1)] {
            if let stream = mesh.stream(semantic) {
                var values = stream.data
                if semantic == .textureCoordinate(0) {
                    for index in stride(from: 1, to: values.count, by: 2) { values[index] = 1 - values[index] }
                }
                arrays.append(object(.attributeArray, [String(type), "0", "2", "0", "0"] + values.map { String($0) }))
            }
        }
        var values = [String(triangles.count), "0", "0", "0", String(mesh.vertexCount), String(arrays.count)]
        values += triangles.flatMap { [String($0.x), String($0.y), String($0.z)] }
        values += mesh.positions.flatMap { [String($0.x), String($0.y), String($0.z)] }
        let bounds = BoundingBox(points: mesh.positions)
        values += [bounds.min.x, bounds.min.y, bounds.min.z, bounds.max.x, bounds.max.y, bounds.max.z].map { String($0) }
        values.append("False")
        let (shader, attributes) = try materialObjects(material)
        arrays.append(object(.attributeSet, children: attributes))
        arrays += try name(submesh.name)
        let culling = material.isDoubleSided ? "0" : material.cullMode == .front ? "3" : "1"
        return object(.displayGroup, children: [
            object(shader), object(.backfacingStyle, [culling]), object(.triMesh, values, children: arrays)
        ])
    }

    private func materialObjects(_ material: MaterialDescriptor) throws(SceneFormatError) -> (MetafileObjectType, [MetafileObject]) {
        guard material.lightingModel != .physicallyBased,
              material.normal.contents == .none, material.ambientOcclusion.contents == .none,
              material.transparent.contents == .none,
              material.blendMode == .alpha, material.writesToDepthBuffer, material.readsFromDepthBuffer,
              material.metalness.contents == .scalar(0), material.roughness.contents == .scalar(0.5),
              material.ambient.color == SIMD4(0, 0, 0, 1) else {
            throw .unsupported("Material features are not supported by 3DMF export")
        }
        var attributes: [MetafileObject] = []
        for (type, property) in [(MetafileObjectType.diffuseColor, material.diffuse),
                                 (.specularColor, material.specular), (.emissiveColor, material.emission)] {
            guard let color = property.color, property.intensity == 1, color.w == 1 else {
                throw .unsupported("3DMF export requires opaque RGB material colors with unit intensity")
            }
            attributes.append(try floats(type, [color.x, color.y, color.z]))
        }
        guard material.shininess >= 1 / 128, (0...1).contains(material.transparency) else {
            throw .unsupported("Material shininess or transparency is outside the supported range")
        }
        attributes.append(try floats(.specularControl, [material.shininess * 128]))
        attributes.append(try floats(.transparencyColor, Array(repeating: material.transparency, count: 3)))
        attributes += try name(material.name)
        let shader: MetafileObjectType = material.lightingModel == .unlit ? .nullIllumination
            : material.lightingModel == .lambert ? .lambertIllumination : .phongIllumination
        return (shader, attributes)
    }
}


/// Why an asset couldn't be read or written.
public enum SceneFormatError: Error, Hashable, Sendable {
    /// The data isn't in the format: a bad magic number, a header out of place.
    case invalidHeader(String)
    /// The data ends before it should.
    case unexpectedEndOfData(offset: Int)
    /// The data is in the format but says something wrong.
    case malformed(String, offset: Int?)
    /// The format allows it, but it isn't read or written yet.
    case unsupported(String)
}

/// Reads an asset format into a scene.
public protocol SceneAssetDecoder {

    /// The file name extensions the format uses, lower case, without the dot.
    static var fileExtensions: [String] { get }

    func decode(_ data: [UInt8]) async throws(SceneFormatError) -> Scene
}

/// Writes a scene in an asset format.
public protocol SceneAssetEncoder {

    static var fileExtensions: [String] { get }

    func encode(_ scene: Scene) async throws(SceneFormatError) -> [UInt8]
}

import BinaryParsing

extension SceneFormatError {

    /// A binary parser's error, as a format error: data ending early, or a value out of range.
    init(_ error: ParsingError) {
        if error.status == .insufficientData {
            self = .unexpectedEndOfData(offset: error.location ?? 0)
        } else if let format = error.userError as? SceneFormatError {
            self = format
        } else {
            self = .malformed("Invalid value", offset: error.location)
        }
    }
}
